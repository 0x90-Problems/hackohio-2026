// Copies the MCP tool list from the board API into shared/mcp-tools.json, so the
// Agents page describes each tool in the backend's own words.
// Run from web/ after a tool is added or reworded in the backend:
//   node scripts/sync-mcp-tools.mjs ../../0x90-NextJS-Backend/src/mcp-http.ts
// Keeps the first sentence of each description (the one-line summary) and the
// scopes named after "Requires".

import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

const OUT = fileURLToPath(new URL("../../shared/mcp-tools.json", import.meta.url))

/** The first sentence, or the whole text when it has no full stop. */
export function summary(description) {
  const match = /^(.+?[.!?])(?:\s|$)/.exec(description)
  return (match ? match[1] : description).trim()
}

/** Scopes from "Requires a, b and c." Human-only tools name no scope. */
export function requiredScopes(description) {
  const match = /Requires ([a-z]+:[a-z]+(?:(?:,\s*|\s+and\s+)[a-z]+:[a-z]+)*)/.exec(description)
  return match ? match[1].split(/,\s*|\s+and\s+/) : []
}

export function parseTools(source) {
  const tools = []
  const entry = /\{\s*name:\s*"([a-z0-9_]+)",\s*description:\s*"((?:[^"\\]|\\.)*)"/g
  for (const [, name, raw] of source.matchAll(entry)) {
    const description = JSON.parse(`"${raw}"`)
    tools.push({ name, description: summary(description), scopes: requiredScopes(description) })
  }
  const hidden = /BOARD_CHAT_TOOLS\s*=\s*new Set\(\[([^\]]*)\]\)/.exec(source)
  const boardChat = hidden ? [...hidden[1].matchAll(/"([a-z0-9_]+)"/g)].map((m) => m[1]) : []
  return { tools, boardChat }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const from = process.argv[2]
  if (!from) {
    console.error("usage: node scripts/sync-mcp-tools.mjs <path to 0x90-NextJS-Backend/src/mcp-http.ts>")
    process.exit(1)
  }
  const { tools, boardChat } = parseTools(readFileSync(from, "utf8"))
  if (tools.length === 0) {
    console.error("No tools found. Has the TOOLS list in mcp-http.ts changed shape?")
    process.exit(1)
  }
  const body = {
    _note: "Generated by web/scripts/sync-mcp-tools.mjs from 0x90-NextJS-Backend src/mcp-http.ts. Do not edit by hand.",
    board_chat_tools: boardChat,
    tools,
  }
  writeFileSync(OUT, JSON.stringify(body, null, 2) + "\n")
  console.log(`Wrote ${tools.length} tools to shared/mcp-tools.json`)
}
